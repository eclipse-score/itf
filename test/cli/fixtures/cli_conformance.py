"""Conformance of acme/toggle: a switch starts off."""

from score.itf.contracts.conformance import check, expect


@check()
def a_switch_starts_off(node):
    expect(node.is_on() is False, "the switch is on although nothing switched it")


CHECKS = {"acme/toggle": [a_switch_starts_off]}
